// Reads the owner's button icon SVGs (data/BUTTON ICONS/<NAME>/ICONS/*.svg) and writes src/app/buttonIcons.js: for each button, the list of
// icons for its dropdown. An icon is a list of [pathData, evenOdd] pairs drawn filled in the current colour on a 42.52 x 42.52 box.
// A shape the file fills white is a cut-out (merged into the shape under it with the even-odd rule); a shape filled "none" is skipped.
// Run: node scripts/active/build_button_icons.js
const fs = require('fs'), path = require('path');
const ROOT = path.join(__dirname, '..', '..');
const SRC = path.join(ROOT, 'data', 'BUTTON ICONS');

// dropdown key -> [[folder, first, last (file number range, inclusive, optional)], ...] in dropdown order
const MAP = {
    volume: [['VOLUME']],
    shuffle: [['SHUFFLE']],
    play: [['PLAY']],
    pause: [['PAUSE']],
    nav: [['NEXT LAST'], ['PLAY', 16, 24]],   // Next / Last: the arrows, then play icons 16-24 (owner's request)
    filter: [['FILTER']],
    tp: [['TEMPO']],
    v: [['VALENCE']],
    dn: [['DANCE']],
    e: [['ENERGY']],
};

const num = f => parseInt((f.match(/-(\d+)\.svg$/) || [])[1], 10);
function parse(file) {
    const s = fs.readFileSync(file, 'utf8');
    const cls = {};
    for (const m of s.matchAll(/\.(cls-\d+)\s*\{([^}]*)\}/g)) {
        const f = (m[2].match(/fill:\s*([^;\s]+)/) || [])[1], eo = /fill-rule:\s*evenodd/.test(m[2]);
        cls[m[1]] = { fill: f || '#000', eo };
    }
    const shapes = [];
    for (const m of s.matchAll(/<(path|polygon)\b([^>]*)\/?>/g)) {
        const at = m[2], c = (at.match(/class="([^"]+)"/) || [])[1], st = cls[c] || { fill: '#000', eo: false };
        if (/transform=|clip-path|stroke/.test(at)) console.warn('  note: transform/stroke in', path.basename(file));
        let d;
        if (m[1] === 'path') d = (at.match(/\sd="([^"]+)"/) || [])[1];
        else { const p = (at.match(/points="([^"]+)"/) || [])[1].trim().split(/[\s,]+/); d = 'M' + p.map((v, i) => (i % 2 ? ' ' : (i ? 'L' : ''))+ v).join('') + 'Z'; }
        if (d) shapes.push({ d, fill: st.fill.toLowerCase(), eo: st.eo });
    }
    const dark = shapes.filter(x => x.fill !== 'none' && x.fill !== '#fff' && x.fill !== '#ffffff');
    const white = shapes.filter(x => x.fill === '#fff' || x.fill === '#ffffff');
    if (!white.length) return dark.map(x => [x.d, x.eo ? 1 : 0]);
    // cut-outs: one even-odd path = the filled shape(s) + the white shape(s)
    return [[dark.map(x => x.d).concat(white.map(x => x.d)).join(''), 1]];
}

const out = {};
for (const [key, srcs] of Object.entries(MAP)) {
    out[key] = [];
    for (const [folder, a, b] of srcs) {
        const dir = path.join(SRC, folder, 'ICONS');
        const files = fs.readdirSync(dir).filter(f => /\.svg$/i.test(f)).sort((x, y) => num(x) - num(y));
        for (const f of files) {
            const n = num(f);
            if (a !== undefined && (n < a || n > b)) continue;
            const icon = parse(path.join(dir, f));
            if (!icon.length) { console.warn('skipped (no shapes):', folder + '/' + f); continue; }
            out[key].push({ n: f.replace(/\.svg$/i, ''), icon });
        }
    }
    console.log(key.padEnd(8), out[key].length, 'icons');
}

let js = '// GENERATED by scripts/active/build_button_icons.js from data/BUTTON ICONS - do not hand-edit; re-run the script.\n'
    + '// For each button: its dropdown icons. An icon is [[pathData, evenOdd], ...] on a 42.52 x 42.52 box, drawn filled in the current colour.\n'
    + 'export const ICON_BOX = 42.52;\nexport const BUTTON_ICONS = {\n';
for (const [key, list] of Object.entries(out)) {
    js += `    ${key}: [\n` + list.map(it => `        { n: ${JSON.stringify(it.n)}, p: ${JSON.stringify(it.icon)} },`).join('\n') + '\n    ],\n';
}
js += '};\n';
fs.writeFileSync(path.join(ROOT, 'src', 'app', 'buttonIcons.js'), js);
console.log('wrote src/app/buttonIcons.js', js.length, 'bytes');

// The dev panel is a classic script that loads before the module graph, so it gets just the names, as a global.
const names = {};
for (const [key, list] of Object.entries(out)) names[key] = list.map(it => it.n);
fs.writeFileSync(path.join(ROOT, 'src', 'devpanel', 'buttonIconNames.js'),
    '// GENERATED by scripts/active/build_button_icons.js - do not hand-edit. Dropdown labels for the imported button icons.\nwindow.SPX_ICON_NAMES = ' + JSON.stringify(names) + ';\n');
console.log('wrote src/devpanel/buttonIconNames.js');
